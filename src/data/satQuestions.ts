// ─── Daily Question Selector ────────────────────────────────────
export function getDailyQuestions(): { reading: SATQuestion; math: SATQuestion } {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((now.getTime() - startOfYear.getTime()) / (1000 * 60 * 60 * 24));

  const readingIndex = dayOfYear % satReadingQuestions.length;
  const mathIndex = dayOfYear % satMathQuestions.length;

  return {
    reading: satReadingQuestions[readingIndex],
    math: satMathQuestions[mathIndex],
  };
}
